-- PostgreSQL translation of ../sqlite/001_init.sql (same schema).
-- Hami schema v1.
-- Observations (what was seen) and inferences (assessments, links, reviews) live in separate
-- tables, so a correction never rewrites what was observed. Reviews and observations are
-- append-only (enforced by triggers below).

CREATE TABLE IF NOT EXISTS scans (
    scan_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submitted_url   TEXT NOT NULL,              -- sanitized (token-like query params stripped)
    normalized_url  TEXT NOT NULL,
    host            TEXT NOT NULL,
    final_url       TEXT,
    source_type     TEXT NOT NULL CHECK (source_type IN
                        ('search','maps','sms','whatsapp','manual','extension','discovery','import')),
    listing_name    TEXT,
    lang            TEXT,                       -- language requested by the client (ar|en)
    batch           TEXT,                       -- bulk capture batch name (legit_urls, labels, ...), NULL for user scans
    parent_scan_id BIGINT REFERENCES scans(scan_id),
    submitted_at    TEXT NOT NULL,
    status          TEXT NOT NULL DEFAULT 'pending' CHECK (status IN
                        ('pending','capturing','analyzing','done','failed')),
    capture_mode    TEXT CHECK (capture_mode IN ('live','stored')),
    capture_status  TEXT,                       -- ok | load_failed | blocked | timeout | refused
    capture_error   TEXT,
    captured_at     TEXT,
    stored_from_scan_id BIGINT REFERENCES scans(scan_id),
    completed_at    TEXT,
    duration_ms     INTEGER,
    page_lang       TEXT,                       -- detected language of the page (ar|en|mixed)
    fingerprint     TEXT,                       -- JSON MinHash of DOM-structure shingles
    form_signature  TEXT,
    payment_signature TEXT
);
CREATE INDEX IF NOT EXISTS idx_scans_norm ON scans(normalized_url, submitted_at);
CREATE INDEX IF NOT EXISTS idx_scans_host ON scans(host);
CREATE INDEX IF NOT EXISTS idx_scans_batch ON scans(batch);

CREATE TABLE IF NOT EXISTS artifacts (
    artifact_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id BIGINT NOT NULL REFERENCES scans(scan_id),
    kind            TEXT NOT NULL CHECK (kind IN
                        ('har','html','screenshot','action_log','analysis','model_text')),
    sha256          TEXT NOT NULL,
    path            TEXT NOT NULL,              -- relative to the artifact store
    size_bytes      INTEGER NOT NULL,
    mime            TEXT,
    captured_at     TEXT NOT NULL,
    action_step     INTEGER,
    action_name     TEXT
);
CREATE INDEX IF NOT EXISTS idx_artifacts_scan ON artifacts(scan_id);

CREATE TABLE IF NOT EXISTS observations (
    obs_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id BIGINT NOT NULL REFERENCES scans(scan_id),
    artifact_id BIGINT REFERENCES artifacts(artifact_id),
    indicator_type  TEXT NOT NULL,
    strength        TEXT NOT NULL DEFAULT 'info' CHECK (strength IN ('strong','medium','weak','info')),
    redacted_excerpt TEXT,
    host_ref        TEXT,
    host_relation   TEXT CHECK (host_relation IN ('referenced','observed','referenced_and_observed')),
    context         TEXT,                       -- e.g. json:domainUrl, html:img[src], traffic:image
    site_reported_time TEXT,                    -- timestamp reported by the site itself, never our capture time
    action_step     INTEGER,
    lang            TEXT,
    details_json    TEXT,
    created_at      TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_obs_scan ON observations(scan_id);
CREATE INDEX IF NOT EXISTS idx_obs_host ON observations(host_ref);
CREATE INDEX IF NOT EXISTS idx_obs_type ON observations(indicator_type);

CREATE TABLE IF NOT EXISTS assessments (
    assessment_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id BIGINT NOT NULL REFERENCES scans(scan_id),
    risk_tier       TEXT NOT NULL CHECK (risk_tier IN
                        ('high_risk','caution','no_strong_signals','insufficient_evidence')),
    score           DOUBLE PRECISION,
    rules_fired     TEXT NOT NULL,              -- JSON list
    clues_json      TEXT NOT NULL,              -- JSON list (max 3 shown to users)
    identity_check  TEXT NOT NULL DEFAULT 'not_checked' CHECK (identity_check IN
                        ('match','mismatch','unclear','not_checked')),
    top_phrases     TEXT,                       -- JSON list of top-weighted model phrases
    model_version   TEXT,
    created_at      TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_assess_scan ON assessments(scan_id);

CREATE TABLE IF NOT EXISTS reviews (
    review_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id BIGINT NOT NULL REFERENCES scans(scan_id),
    label           TEXT NOT NULL CHECK (label IN ('fraudulent','legitimate','inconclusive')),
    behavior_tags   TEXT NOT NULL DEFAULT '[]', -- JSON list
    scam_type       TEXT,
    notes           TEXT,
    reviewer        TEXT NOT NULL,
    supersedes BIGINT REFERENCES reviews(review_id),
    training_eligible INTEGER NOT NULL DEFAULT 0,
    created_at      TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_reviews_scan ON reviews(scan_id);

CREATE TABLE IF NOT EXISTS dataset_versions (
    version         TEXT PRIMARY KEY,
    created_at      TEXT NOT NULL,
    kind            TEXT NOT NULL CHECK (kind IN ('full','synthetic')),
    record_count    INTEGER NOT NULL,
    label_counts    TEXT NOT NULL,              -- JSON
    sources         TEXT NOT NULL,              -- JSON counts per origin/source
    dataset_hash    TEXT NOT NULL,
    snapshot_path   TEXT
);

CREATE TABLE IF NOT EXISTS model_versions (
    version         TEXT PRIMARY KEY,
    created_at      TEXT NOT NULL,
    status          TEXT NOT NULL CHECK (status IN ('candidate','current','retired')),
    dataset_version TEXT REFERENCES dataset_versions(version),
    dataset_hash    TEXT NOT NULL,
    metrics_json    TEXT NOT NULL,
    feature_settings TEXT NOT NULL,
    promotion_json  TEXT,                       -- the promotion-rule comparison that was applied
    path            TEXT NOT NULL,
    promoted_at     TEXT,
    retired_at      TEXT
);

CREATE TABLE IF NOT EXISTS links (
    link_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_a BIGINT NOT NULL REFERENCES scans(scan_id),
    scan_b BIGINT NOT NULL REFERENCES scans(scan_id),
    host_a          TEXT NOT NULL,
    host_b          TEXT NOT NULL,
    relation_type   TEXT NOT NULL,              -- strongest relation (registration_destination, asset_host, ...)
    strength        TEXT NOT NULL CHECK (strength IN ('strong','medium')),
    evidence_obs_ids TEXT NOT NULL,             -- JSON list of observation ids
    evidence_json   TEXT NOT NULL,              -- JSON list of signals
    review_status   TEXT NOT NULL DEFAULT 'pending' CHECK (review_status IN ('pending','approved','rejected')),
    reviewed_by     TEXT,
    reviewed_at     TEXT,
    review_note     TEXT,
    created_at      TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_links_a ON links(scan_a);
CREATE INDEX IF NOT EXISTS idx_links_b ON links(scan_b);

CREATE TABLE IF NOT EXISTS watches (
    watch_id        TEXT PRIMARY KEY,           -- random UUID
    scan_id BIGINT NOT NULL REFERENCES scans(scan_id),
    host            TEXT NOT NULL,              -- a watch follows the case (site), not one capture
    device_id       TEXT NOT NULL,              -- random device UUID, pseudonymous
    created_at      TEXT NOT NULL,
    deleted_at      TEXT
);
CREATE INDEX IF NOT EXISTS idx_watches_device ON watches(device_id);
CREATE INDEX IF NOT EXISTS idx_watches_host ON watches(host);

CREATE TABLE IF NOT EXISTS alerts (
    alert_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    link_id BIGINT NOT NULL REFERENCES links(link_id),
    watched_host    TEXT NOT NULL,
    watched_scan_id BIGINT NOT NULL REFERENCES scans(scan_id),
    related_scan_id BIGINT NOT NULL REFERENCES scans(scan_id),
    reason_en       TEXT NOT NULL,
    reason_ar       TEXT NOT NULL,
    status          TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','withdrawn','cancelled')),
    created_at      TEXT NOT NULL,
    approved_by     TEXT,
    approved_at     TEXT,
    sent_at         TEXT,
    withdrawn_at    TEXT,
    withdrawn_by    TEXT,
    withdrawn_reason TEXT,
    UNIQUE (link_id, watched_host)
);

CREATE TABLE IF NOT EXISTS discovered_domains (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain          TEXT NOT NULL UNIQUE,
    source          TEXT NOT NULL DEFAULT 'ct' CHECK (source IN ('ct','har_reference','manual')),
    cert_seen_at    TEXT,                       -- certificate not_before / log entry time (CT source)
    first_seen_at   TEXT NOT NULL,              -- when Hami first saw the name
    matched_pattern TEXT,
    evidence        TEXT,                       -- JSON (e.g. which artifact referenced it)
    scan_id BIGINT REFERENCES scans(scan_id),
    status          TEXT NOT NULL DEFAULT 'queued' CHECK (status IN
                        ('awaiting_approval','queued','scanning','scanned','failed','skipped')),
    status_note     TEXT,
    updated_at      TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS static_findings (
    finding_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category        TEXT NOT NULL,              -- aws_access_key, private_key, generic_secret, ...
    rule            TEXT NOT NULL,
    file_path       TEXT NOT NULL,              -- relative to the authorized root
    line            INTEGER NOT NULL,
    col             INTEGER NOT NULL,
    related_host    TEXT,
    detected_at     TEXT NOT NULL,
    review_status   TEXT NOT NULL DEFAULT 'pending' CHECK (review_status IN ('pending','confirmed','dismissed')),
    reviewed_by     TEXT,
    reviewed_at     TEXT,
    UNIQUE (file_path, line, col, rule)
    -- Deliberately no column for the secret value.
);

-- Append-only guarantees.
CREATE OR REPLACE FUNCTION reviews_no_update_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'reviews are append-only; add a new review that supersedes it'; END; $$;
DROP TRIGGER IF EXISTS reviews_no_update ON reviews;
CREATE TRIGGER reviews_no_update BEFORE UPDATE ON reviews FOR EACH ROW EXECUTE FUNCTION reviews_no_update_fn();
CREATE OR REPLACE FUNCTION reviews_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'reviews are append-only'; END; $$;
DROP TRIGGER IF EXISTS reviews_no_delete ON reviews;
CREATE TRIGGER reviews_no_delete BEFORE DELETE ON reviews FOR EACH ROW EXECUTE FUNCTION reviews_no_delete_fn();
CREATE OR REPLACE FUNCTION observations_no_update_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'observations are immutable'; END; $$;
DROP TRIGGER IF EXISTS observations_no_update ON observations;
CREATE TRIGGER observations_no_update BEFORE UPDATE ON observations FOR EACH ROW EXECUTE FUNCTION observations_no_update_fn();
CREATE OR REPLACE FUNCTION artifacts_no_update_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'artifacts are immutable'; END; $$;
DROP TRIGGER IF EXISTS artifacts_no_update ON artifacts;
CREATE TRIGGER artifacts_no_update BEFORE UPDATE ON artifacts FOR EACH ROW EXECUTE FUNCTION artifacts_no_update_fn();
