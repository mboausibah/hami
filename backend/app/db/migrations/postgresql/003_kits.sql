-- PostgreSQL translation of ../sqlite/003_kits.sql (same schema).
-- Kit fingerprinting from delivered files, delivered-code observations, idle snapshots.

-- Every JS/CSS/font/image/JSON file a page delivered, identified by SHA-256 (computed before the
-- sanitizer drops binary bodies), file name (content-hashed build names are fingerprints too) and, for
-- text bundles, a bottom-k shingle sketch for near-identical matching.
CREATE TABLE IF NOT EXISTS asset_files (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id BIGINT NOT NULL REFERENCES scans(scan_id),
    host            TEXT NOT NULL,
    site            TEXT NOT NULL,             -- registrable domain of the page that loaded it
    file_name       TEXT NOT NULL,
    chunk_name      TEXT,                      -- build chunk without its content hash (e.g. en-US, views-vipNew)
    name_hashed     INTEGER NOT NULL DEFAULT 0,
    kind            TEXT NOT NULL,             -- js | css | font | image | json | other
    sha256          TEXT NOT NULL,
    size_bytes      INTEGER,
    sketch          TEXT,                      -- JSON bottom-k shingle hashes (text bundles only)
    source          TEXT NOT NULL DEFAULT 'capture',   -- capture | snapshot | session
    created_at      TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_assets_sha ON asset_files(sha256);
CREATE INDEX IF NOT EXISTS idx_assets_name ON asset_files(file_name);
CREATE INDEX IF NOT EXISTS idx_assets_chunk ON asset_files(chunk_name);
CREATE INDEX IF NOT EXISTS idx_assets_scan ON asset_files(scan_id);
CREATE INDEX IF NOT EXISTS idx_assets_site ON asset_files(site);

-- Where an observation came from: the visible page, the site's delivered code, asset file names, traffic.
ALTER TABLE observations ADD COLUMN IF NOT EXISTS source TEXT NOT NULL DEFAULT 'visible_page';

-- Classifier score on the delivered-code text (separate from the visible-page score).
ALTER TABLE assessments ADD COLUMN IF NOT EXISTS code_score DOUBLE PRECISION;

-- Idle snapshots sent by the extension (metadata only; the HAR-format artifact holds the details).
CREATE TABLE IF NOT EXISTS snapshots (
    snapshot_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id BIGINT NOT NULL REFERENCES scans(scan_id),
    page_host       TEXT NOT NULL,
    resource_count  INTEGER NOT NULL,
    host_count      INTEGER NOT NULL,
    fetched_count   INTEGER NOT NULL DEFAULT 0,
    created_at      TEXT NOT NULL
);

-- Evidence HAR files uploaded from investigator mode (sanitized on the device).
CREATE TABLE IF NOT EXISTS evidence_files (
    evidence_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id BIGINT REFERENCES scans(scan_id),
    page_host       TEXT NOT NULL,
    artifact_id BIGINT NOT NULL REFERENCES artifacts(artifact_id),
    client_sha256   TEXT NOT NULL,             -- hash computed on the device before upload
    server_sha256   TEXT NOT NULL,
    entries         INTEGER NOT NULL,
    created_at      TEXT NOT NULL
);
